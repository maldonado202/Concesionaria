    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        //controlo que la tabla no este vacia
        if(tablaAutos.getRowCount() > 0){
            //valido que se haya seleccionado un registro
            if(tablaAutos.getSelectedRow() != -1){
                //obtengo el id del auto que quiero borrar, creo una variable auxiliar
                int idAuto = Integer.parseInt(String.valueOf(tablaAutos.getValueAt(tablaAutos.getSelectedRow(),0))); //columna 0
                
                control.borrarAuto(idAuto);
                mostrarMensaje("Borrado correctamente", "Info", "Borrado");
                cargarTabla();
            }
            else{
                mostrarMensaje("Se debe seleccionar un registro", "Error", "Error al eliminar");
            }
        }
        else{
            mostrarMensaje("Tabla vacia, no se puede eliminar", "Error", "Error al eliminar");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

