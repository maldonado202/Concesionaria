    private void cargarTabla() {
        //hago la tabla no editable
          DefaultTableModel modeloTabla = new DefaultTableModel(){
              @Override//sobreescritura de metodos; hace que el metodo que tenga por defecto DefaultTableModel
                       //lo sobreescriba por isCellEditable, que se ponga todo en falso y no se pueda editar
                       //la tabla
              public boolean isCellEditable(int row, int column){
                  return false;//hace que la fila y columna no sean editables 
              }
              
          };//punto y coma porque es una porcion de codigo
          
          //PONGO TITULOS A LAS COLUMNAS
          String titulos[] = {"Id","Modelo","Marca","Motor","Color","Patente","Puertas"};
          modeloTabla.setColumnIdentifiers(titulos);//en mi tabla establesco los identifiadores de columnas
                                                    //titulos
          //traigo los autos desde la base de datos. Carga del lado del backend
          List<Automovil> listaAutomoviles = control.traerAutos();
          
          //setear los datos en la tabla
          if(listaAutomoviles != null){
              for(Automovil auto : listaAutomoviles){
                  //creo objeto generico de tipo object
                  Object[] objeto = {auto.getId(),auto.getModelo(),auto.getMarca(),
                                      auto.getMotor(),auto.getColor(),auto.getPatente(),
                                      auto.getCantPuertas()};
                  
                 modeloTabla.addRow(objeto);//agrego el objeto como fila
              }
          }
                                                    
                                                    
          
                                                    
          tablaAutos.setModel(modeloTabla);//paso el valor de las columnas, los nombres
          
    }
