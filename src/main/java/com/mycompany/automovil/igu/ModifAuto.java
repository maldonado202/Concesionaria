    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnModificarActionPerformed
        //traigo los datos del auto
        String modelo = txtModelo.getText();
        String marca = txtMarca.getText();
        String motor = txtMotor.getText();
        String color = txtColor.getText();
        String patente = txtPatente.getText();
        int cantPuertas = Integer.parseInt(txtCantPuertas.getText());
        //auto seria el original sin cambios, el resto serian los nuevos valores
        control.modificarAuto(auto, modelo, marca, motor, color, patente, cantPuertas);
        mostrarMensaje("Edicion realizada con exito","Info","Edicion exitosa");
        txtModelo.setText("");
        txtMarca.setText("");
        txtMotor.setText("");
        txtColor.setText("");
        txtPatente.setText("");
        txtCantPuertas.setText("");
        ConsultaAutomovil consu = new ConsultaAutomovil();
        consu.setVisible(true);
        consu.setLocationRelativeTo(null);
        this.dispose();
        

    }//GEN-LAST:event_btnModificarActionPerformed

